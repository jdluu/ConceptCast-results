from manim import *

class SceneGen(Scene):
    def construct(self):
        # Scene 1: Forward Pass
        title = Text("1. Forward Pass in a Neural Network").to_edge(UP)
        self.play(Write(title))
        x = Circle(radius=0.4).shift(LEFT*3).set_color(BLUE).set_fill(BLUE, opacity=0.4)
        h = Circle(radius=0.4).shift(ORIGIN).set_color(GREEN).set_fill(GREEN, opacity=0.4)
        y = Circle(radius=0.4).shift(RIGHT*3).set_color(RED).set_fill(RED, opacity=0.4)
        x_l = MathTex("x").next_to(x, UP)
        h_l = MathTex("h").next_to(h, UP)
        y_l = MathTex("\\hat{y}").next_to(y, UP)
        self.play(Create(x), Create(h), Create(y), Write(x_l), Write(h_l), Write(y_l))
        e1 = Arrow(x, h, buff=0.4, color=WHITE)
        e2 = Arrow(h, y, buff=0.4, color=WHITE)
        w1 = MathTex("w_1").next_to(e1, UP)
        w2 = MathTex("w_2").next_to(e2, UP)
        self.play(Create(e1), Create(e2), Write(w1), Write(w2))
        dot1 = Dot(color=YELLOW).move_to(x)
        self.play(dot1.animate.move_to(h), run_time=1.5)
        dot2 = Dot(color=YELLOW).move_to(h)
        self.play(dot2.animate.move_to(y), run_time=1.5)
        self.play(FadeOut(dot1, dot2))
        eq = MathTex("h = \\sigma(w_1 x)", "\\quad \\hat{y} = w_2 h").to_edge(DOWN)
        self.play(Write(eq))
        self.wait(1)

        self.clear()

        # Scene 2: Loss
        title2 = Text("2. Compute the Loss").to_edge(UP)
        self.play(Write(title2))
        y_hat = MathTex("\\hat{y}").set_color(RED).shift(LEFT*2)
        y_true = MathTex("y_{true}").set_color(BLUE).shift(RIGHT*2)
        arr = Arrow(y_hat, y_true, color=WHITE)
        self.play(Write(y_hat), Write(y_true), Create(arr))
        diff = MathTex("\\Delta = y_{true} - \\hat{y}").next_to(arr, UP)
        self.play(Write(diff))
        loss = MathTex("L = (y_{true} - \\hat{y})^2").shift(DOWN*1.5)
        self.play(Write(loss))
        self.wait(1)

        self.clear()

        # Scene 3: Chain Rule
        title3 = Text("3. The Chain Rule").to_edge(UP)
        self.play(Write(title3))
        f = MathTex("L = f(g(w))").shift(UP*1.5)
        self.play(Write(f))
        cr = MathTex("\\frac{dL}{dw} = \\frac{dL}{dg} \\cdot \\frac{dg}{dw}").shift(DOWN*0.5)
        self.play(Write(cr))
        b1 = Square(side_length=1).shift(LEFT*2).set_color(YELLOW)
        b2 = Square(side_length=1).shift(RIGHT*2).set_color(GREEN)
        l1 = MathTex("g").next_to(b1, UP)
        l2 = MathTex("f").next_to(b2, UP)
        a = Arrow(b1, b2)
        self.play(Create(b1), Create(b2), Write(l1), Write(l2), Create(a))
        self.wait(1)

        self.clear()

        # Scene 4: Output Gradient
        title4 = Text("4. Gradient at Output Layer").to_edge(UP)
        self.play(Write(title4))
        eq1 = MathTex("\\frac{\\partial L}{\\partial w_2} = \\frac{\\partial L}{\\partial \\hat{y}} \\frac{\\partial \\hat{y}}{\\partial w_2}").shift(UP)
        self.play(Write(eq1))
        eq2 = MathTex("\\frac{\\partial L}{\\partial \\hat{y}} = -2(y_{true} - \\hat{y})").shift(DOWN)
        eq3 = MathTex("\\frac{\\partial \\hat{y}}{\\partial w_2} = h").shift(DOWN*1.5)
        self.play(Write(eq2), Write(eq3))
        res = MathTex("\\frac{\\partial L}{\\partial w_2} = -2(y_{true} - \\hat{y}) h").shift(DOWN*3)
        self.play(Write(res))
        self.wait(1)

        self.clear()

        # Scene 5: Backprop to Hidden
        title5 = Text("5. Backpropagate to Hidden Layer").to_edge(UP)
        self.play(Write(title5))
        e1 = MathTex("\\frac{\\partial L}{\\partial w_1} = \\frac{\\partial L}{\\partial h} \\frac{\\partial h}{\\partial w_1}").shift(UP*1.5)
        self.play(Write(e1))
        e2 = MathTex("\\frac{\\partial L}{\\partial h} = \\frac{\\partial L}{\\partial \\hat{y}} \\frac{\\partial \\hat{y}}{\\partial h} = \\frac{\\partial L}{\\partial \\hat{y}} w_2").shift(DOWN*0.2)
        self.play(Write(e2))
        e3 = MathTex("\\frac{\\partial h}{\\partial w_1} = x \\sigma'(w_1 x)").shift(DOWN*1.5)
        self.play(Write(e3))
        back_arrow = Arrow(UP*0.8, DOWN*0.8, color=YELLOW).shift(RIGHT*4)
        self.play(Create(back_arrow))
        self.wait(1)

        self.clear()

        # Scene 6: Weight Update
        title6 = Text("6. Gradient Descent Update").to_edge(UP)
        self.play(Write(title6))
        w_gen = MathTex("w \\leftarrow w - \\eta \\frac{\\partial L}{\\partial w}").shift(UP*1.5)
        self.play(Write(w_gen))
        w2u = MathTex("w_2 \\leftarrow w_2 - \\eta \\frac{\\partial L}{\\partial w_2}").shift(DOWN*0.2)
        w1u = MathTex("w_1 \\leftarrow w_1 - \\eta \\frac{\\partial L}{\\partial w_1}").shift(DOWN*1.5)
        self.play(Write(w2u))
        self.play(Write(w1u))
        lr = MathTex("\\eta = 0.1 \\text{ (learning rate)}").set_color(YELLOW).shift(RIGHT*3 + UP)
        self.play(Write(lr))
        self.wait(1)

        self.clear()

        # Scene 7: Full Loop
        title7 = Text("7. Training Loop: Forward & Backward").to_edge(UP)
        self.play(Write(title7))
        xc = Circle(radius=0.3).shift(LEFT*4).set_color(BLUE)
        hc = Circle(radius=0.3).shift(LEFT*1).set_color(GREEN)
        yc = Circle(radius=0.3).shift(RIGHT*2).set_color(RED)
        self.play(Create(xc), Create(hc), Create(yc))
        edges = VGroup(Arrow(xc, hc, buff=0.3, color=WHITE), Arrow(hc, yc, buff=0.3, color=WHITE))
        self.play(Create(edges))
        fwd = Text("Forward Pass").set_color(GREEN).next_to(edges, UP)
        self.play(Write(fwd))
        self.play(FadeOut(fwd))
        bwd = Text("Backward Pass (Backprop)").set_color(RED).next_to(edges, DOWN)
        self.play(Write(bwd))
        self.play(FadeOut(bwd))
        loop = MathTex("\\text{Repeat: Forward} \\rightarrow \\text{Loss} \\rightarrow \\text{Backward} \\rightarrow \\text{Update}").shift(DOWN*2)
        self.play(Write(loop))
        self.wait(1)