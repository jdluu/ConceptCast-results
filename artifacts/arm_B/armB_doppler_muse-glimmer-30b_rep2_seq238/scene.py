from manim import *

class SceneGen(Scene):
    def construct(self):
        # Scene 1: Introduction
        title = Text("The Doppler Effect", font_size=64)
        subtitle = Text("Apparent frequency shift due to relative motion", font_size=32).next_to(title, DOWN)
        intro = VGroup(title, subtitle).arrange(DOWN, aligned_edge=LEFT, buff=0.5)
        self.play(Write(title), Write(subtitle))
        self.wait(1)
        self.play(FadeOut(intro))
        self.clear()

        # Scene 2: Wave concept stationary
        title2 = Text("1. Waves from a stationary source", font_size=48)
        self.play(Write(title2))
        source = Dot(color=BLUE, radius=0.15).shift(LEFT*3)
        source_label = Text("Source", font_size=24).next_to(source, DOWN)
        observer = Dot(color=RED, radius=0.15).shift(RIGHT*3)
        observer_label = Text("Observer", font_size=24).next_to(observer, DOWN)
        self.play(FadeIn(source), Write(source_label), FadeIn(observer), Write(observer_label))
        wave1 = Circle(radius=0.5, color=GREEN).move_to(source)
        wave2 = Circle(radius=1.0, color=GREEN).move_to(source)
        wave3 = Circle(radius=1.5, color=GREEN).move_to(source)
        self.play(Create(wave1), Create(wave2), Create(wave3))
        self.play(wave1.animate.scale(1.5), wave2.animate.scale(1.5), wave3.animate.scale(1.5), run_time=1.5)
        note = Text("Equal spacing = constant frequency", font_size=28).to_edge(DOWN)
        self.play(Write(note))
        self.wait(1)
        self.clear()

        # Scene 3: Source moving toward observer
        title3 = Text("2. Source moving toward observer", font_size=48)
        self.play(Write(title3))
        source_m = Dot(color=BLUE, radius=0.15).shift(LEFT*3)
        obs_m = Dot(color=RED, radius=0.15).shift(RIGHT*3)
        self.play(FadeIn(source_m), FadeIn(obs_m))
        wave_a = Circle(radius=0.6, color=YELLOW).move_to(source_m)
        wave_b = Circle(radius=0.6, color=YELLOW).move_to(source_m.get_center()+RIGHT*0.3)
        self.play(Create(wave_a))
        self.play(source_m.animate.shift(RIGHT*0.5), wave_a.animate.shift(RIGHT*0.5))
        self.play(Create(wave_b))
        self.play(wave_a.animate.scale(1.2), wave_b.animate.scale(1.2), run_time=1)
        arrow = Arrow(source_m.get_center(), obs_m.get_center(), color=WHITE)
        label = Text("Waves compressed ahead", font_size=28).next_to(arrow, UP)
        self.play(GrowArrow(arrow), Write(label))
        self.wait(1)
        self.clear()

        # Scene 4: Source moving away
        title4 = Text("3. Source moving away from observer", font_size=48)
        self.play(Write(title4))
        source_a = Dot(color=BLUE, radius=0.15).shift(LEFT*2)
        obs_a = Dot(color=RED, radius=0.15).shift(RIGHT*3)
        self.play(FadeIn(source_a), FadeIn(obs_a))
        w1 = Circle(radius=0.6, color=YELLOW).move_to(source_a)
        w2 = Circle(radius=0.6, color=YELLOW).move_to(source_a.get_center()+LEFT*0.4)
        self.play(Create(w1))
        self.play(source_a.animate.shift(LEFT*0.5), w1.animate.shift(LEFT*0.5))
        self.play(Create(w2))
        self.play(w1.animate.scale(1.2), w2.animate.scale(1.2), run_time=1)
        arrow2 = Arrow(source_a.get_center(), obs_a.get_center(), color=WHITE)
        label2 = Text("Waves stretched ahead", font_size=28).next_to(arrow2, UP)
        self.play(GrowArrow(arrow2), Write(label2))
        self.wait(1)
        self.clear()

        # Scene 5: Observer moving toward source
        title5 = Text("4. Observer moving toward source", font_size=48)
        self.play(Write(title5))
        source_o = Dot(color=BLUE, radius=0.15).shift(LEFT*3)
        observer_o = Dot(color=RED, radius=0.15).shift(RIGHT*2)
        self.play(FadeIn(source_o), FadeIn(observer_o))
        waves = VGroup(*[Circle(radius=0.4+i*0.5, color=GREEN).move_to(source_o) for i in range(4)])
        self.play(LaggedStart(*[Create(w) for w in waves], lag_ratio=0.2))
        self.play(observer_o.animate.shift(LEFT*1.5), run_time=2)
        note_o = Text("Observer meets waves faster", font_size=28).to_edge(DOWN)
        self.play(Write(note_o))
        self.wait(1)
        self.clear()

        # Scene 6: Formula
        title6 = Text("5. Doppler Formula", font_size=48)
        self.play(Write(title6))
        formula = MathTex(r"f' = f \frac{v \pm v_o}{v \mp v_s}", font_size=72)
        self.play(Write(formula))
        exp1 = MathTex(r"v_o \text{ toward source} \;\Rightarrow\; f' > f", font_size=36).next_to(formula, DOWN)
        exp2 = MathTex(r"v_s \text{ toward observer} \;\Rightarrow\; f' > f", font_size=36).next_to(exp1, DOWN)
        self.play(Write(exp1), Write(exp2))
        self.wait(1.5)
        self.clear()

        # Scene 7: Summary
        title7 = Text("Summary", font_size=64)
        bullet1 = Text("Motion changes wavefront spacing", font_size=32)
        bullet2 = Text("Toward = higher frequency, shorter wavelength", font_size=32)
        bullet3 = Text("Away = lower frequency, longer wavelength", font_size=32)
        summary = VGroup(title7, bullet1, bullet2, bullet3).arrange(DOWN, aligned_edge=LEFT, buff=0.4)
        self.play(Write(summary))
        self.wait(2)
