from manim import *

class SceneGen(Scene):
    def construct(self):
        # Scene 1: Introduction to vectors
        self.clear()
        title = Text("Eigenvectors: Direction Preserving Vectors", font_size=36)
        title.to_edge(UP)
        intro = Text("A vector is an arrow with magnitude and direction", font_size=28).next_to(title, DOWN, buff=0.8)
        v1 = Arrow(start=ORIGIN, end=RIGHT*2+UP*1, color=BLUE, buff=0)
        v2 = Arrow(start=ORIGIN, end=RIGHT*1.5, color=GREEN, buff=0)
        v_label = MathTex(r"\mathbf{v}").next_to(v1.get_end(), RIGHT*0.2)
        self.play(Write(title), Write(intro))
        self.play(Create(v1), Create(v2), Write(v_label))
        self.wait(1)
        self.play(FadeOut(title), FadeOut(intro), FadeOut(v1), FadeOut(v2), FadeOut(v_label))

        # Scene 2: Linear transformation
        self.clear()
        t_title = Text("Linear Transformation", font_size=36).to_edge(UP)
        matrix = MathTex(r"A = \begin{pmatrix} a & b \\ c & d \end{pmatrix}").scale(1.2).next_to(t_title, DOWN, buff=0.8)
        arrow = Arrow(start=LEFT*3, end=RIGHT*3, color=YELLOW, buff=0)
        arrow_label = Text("T(v) = A v").next_to(arrow, DOWN)
        self.play(Write(t_title), Write(matrix))
        self.play(Create(arrow), Write(arrow_label))
        self.wait(1)
        self.play(FadeOut(t_title), FadeOut(matrix), FadeOut(arrow), FadeOut(arrow_label))

        # Scene 3: Apply to generic vector
        self.clear()
        t_title2 = Text("Apply A to a vector", font_size=36).to_edge(UP)
        v_generic = Arrow(start=ORIGIN, end=RIGHT*2+UP*1.5, color=BLUE)
        v_label2 = MathTex(r"\mathbf{v}").next_to(v_generic.get_end(), UR*0.2)
        transformed = Arrow(start=ORIGIN, end=RIGHT*3+UP*0.5, color=RED)
        t_label = MathTex(r"A\mathbf{v}").next_to(transformed.get_end(), UR*0.2)
        equals = MathTex("=").next_to(v_generic, RIGHT, buff=2)
        self.play(Write(t_title2), Create(v_generic), Write(v_label2))
        self.play(Write(equals))
        self.play(Create(transformed), Write(t_label))
        self.wait(1)
        self.play(FadeOut(t_title2), FadeOut(v_generic), FadeOut(v_label2), FadeOut(transformed), FadeOut(t_label), FadeOut(equals))

        # Scene 4: Direction change vs scaling
        self.clear()
        dir_title = Text("Most vectors change direction", font_size=36).to_edge(UP)
        v_a = Arrow(start=ORIGIN, end=RIGHT*2, color=BLUE)
        v_a_label = MathTex(r"\mathbf{v}").next_to(v_a.get_end(), RIGHT)
        v_a_trans = Arrow(start=ORIGIN, end=RIGHT*2+UP*1.2, color=RED)
        v_a_trans_label = MathTex(r"A\mathbf{v}").next_to(v_a_trans.get_end(), UR)
        self.play(Write(dir_title), Create(v_a), Write(v_a_label))
        self.play(Transform(v_a, v_a_trans), Transform(v_a_label, v_a_trans_label))
        self.wait(1)
        self.play(FadeOut(dir_title), FadeOut(v_a), FadeOut(v_a_label))

        # Scene 5: Eigenvector definition
        self.clear()
        def_title = Text("Eigenvector Definition", font_size=36).to_edge(UP)
        def_eq = MathTex(r"A\mathbf{v} = \lambda \mathbf{v}").scale(1.4).next_to(def_title, DOWN, buff=0.8)
        def_text = Text("Direction stays the same, only length scales", font_size=28).next_to(def_eq, DOWN, buff=0.6)
        lambda_text = MathTex(r"\lambda").set_color(ORANGE).next_to(def_eq, LEFT*2)
        lambda_label = Text("eigenvalue").next_to(lambda_text, DOWN)
        v_text = MathTex(r"\mathbf{v}").set_color(GREEN).next_to(def_eq, RIGHT*2)
        v_label2 = Text("eigenvector").next_to(v_text, DOWN)
        self.play(Write(def_title), Write(def_eq))
        self.play(Write(def_text))
        self.play(Write(lambda_text), Write(lambda_label), Write(v_text), Write(v_label2))
        self.wait(1.5)
        self.play(FadeOut(def_title), FadeOut(def_eq), FadeOut(def_text), FadeOut(lambda_text), FadeOut(lambda_label), FadeOut(v_text), FadeOut(v_label2))

        # Scene 6: Concrete example
        self.clear()
        ex_title = Text("Example: Diagonal Matrix", font_size=36).to_edge(UP)
        ex_matrix = MathTex(r"A = \begin{pmatrix} 2 & 0 \\ 0 & 1 \end{pmatrix}").next_to(ex_title, DOWN, buff=0.8)
        e1 = Arrow(start=ORIGIN, end=RIGHT*2.5, color=GREEN)
        e1_label = MathTex(r"\mathbf{e}_1").next_to(e1.get_end(), RIGHT)
        e1_trans = Arrow(start=ORIGIN, end=RIGHT*5, color=RED)
        e1_trans_label = MathTex(r"2\mathbf{e}_1").next_to(e1_trans.get_end(), RIGHT)
        e2 = Arrow(start=ORIGIN, end=UP*2.5, color=BLUE)
        e2_label = MathTex(r"\mathbf{e}_2").next_to(e2.get_tip(), UP)
        e2_trans = Arrow(start=ORIGIN, end=UP*2.5, color=RED)
        e2_trans_label = MathTex(r"1\mathbf{e}_2").next_to(e2_trans.get_tip(), UP)
        self.play(Write(ex_title), Write(ex_matrix))
        self.play(Create(e1), Write(e1_label))
        self.play(Transform(e1, e1_trans), Transform(e1_label, e1_trans_label))
        self.play(Create(e2), Write(e2_label))
        self.play(Transform(e2, e2_trans), Transform(e2_label, e2_trans_label))
        self.wait(1)
        self.play(FadeOut(ex_title), FadeOut(ex_matrix), FadeOut(e1), FadeOut(e1_label), FadeOut(e2), FadeOut(e2_label))

        # Scene 7: Summary
        self.clear()
        sum_title = Text("Eigenvectors Preserve Direction", font_size=36).to_edge(UP)
        sum_eq = MathTex(r"A\mathbf{v} = \lambda \mathbf{v} \quad \text{with } \mathbf{v}\neq 0").scale(1.2).next_to(sum_title, DOWN, buff=1)
        sum_text = Text("Non-zero vectors only stretched, not rotated", font_size=28).next_to(sum_eq, DOWN, buff=0.8)
        self.play(Write(sum_title), Write(sum_eq), Write(sum_text))
        self.wait(2)
        self.play(FadeOut(sum_title), FadeOut(sum_eq), FadeOut(sum_text))
